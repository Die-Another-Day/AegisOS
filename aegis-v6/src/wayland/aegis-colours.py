#!/usr/bin/env python3
"""AegisOS v5 wallpaper colour pipeline (original; Pillow only, no matugen).

Reads the current wallpaper, extracts a dominant colour and a saturated
accent, derives light/dark tonal variants with colorsys, and writes:
  ~/.config/aegis/theme.json   — machine-readable palette
  ~/.config/aegis/theme.css    — GTK CSS variables the shell loads
  ~/.config/aegis/blurred.png  — pre-blurred wallpaper (sway has no live
                                 blur, so panels use this as background)
  ~/.config/aegis/blurred-top.png — pre-blurred top strip for the top bar
Usage: aegis-colours.py [wallpaper] [--out DIR]
Default wallpaper: ~/.config/aegis/wallpaper.png (symlink to the active one).
"""
import colorsys, json, os, sys
from pathlib import Path
from PIL import Image, ImageFilter

def clamp(x): return max(0.0, min(1.0, x))

def variants(hexcol):
    r, g, b = (int(hexcol[i:i+2], 16) / 255.0 for i in (1, 3, 5))
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    def hx(hh, ll, ss):
        rr, gg, bb = colorsys.hls_to_rgb(hh % 1.0, clamp(ll), clamp(ss))
        return "#%02x%02x%02x" % (int(rr*255), int(gg*255), int(bb*255))
    return {
        "base": hexcol,
        "light": hx(h, l + 0.28, s * 0.8),
        "dark": hx(h, max(0.05, l - 0.22), s),
        "soft": hx(h, l + 0.12, s * 0.6),
        "on": "#ffffff" if l < 0.6 else "#101018",
    }

def main():
    home = Path.home()
    cfg = home / ".config" / "aegis"
    outdir = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else cfg
    args = [a for a in sys.argv[1:] if not a.startswith("--") and a != str(outdir)]
    wp = Path(args[0]) if args else cfg / "wallpaper.png"
    if not wp.exists():
        print(f"aegis-colours: wallpaper not found: {wp}", file=sys.stderr)
        return 2
    outdir.mkdir(parents=True, exist_ok=True)
    img = Image.open(wp).convert("RGB")
    small = img.copy(); small.thumbnail((96, 96))
    colors = small.getcolors(maxcolors=96*96)
    colors.sort(reverse=True)
    # dominant = most common non-near-black pixel cluster
    dom = None
    for count, (r, g, b) in colors:
        if r + g + b > 60:
            dom = (r, g, b); break
    if dom is None:
        dom = colors[0][1]
    # accent = most saturated colour among the top colours, preferring
    # mid-lightness so a dark wallpaper still gets a visible accent
    def _score(rgb):
        r, g, b = (c / 255.0 for c in rgb)
        h, l, s = colorsys.rgb_to_hls(r, g, b)
        return s * (1.0 - abs(l - 0.55))
    acc = max(colors[:60], key=lambda c: _score(c[1]))[1]
    dom_hex = "#%02x%02x%02x" % dom
    acc_hex = "#%02x%02x%02x" % acc
    # A very dark accent is invisible as a UI accent: lift it to its
    # light tonal variant (still derived from the same wallpaper hue).
    _r, _g, _b = (int(acc_hex[i:i+2], 16) / 255.0 for i in (1, 3, 5))
    _h, _l, _s = colorsys.rgb_to_hls(_r, _g, _b)
    if _l < 0.30:
        acc_hex = variants(acc_hex)["light"]
    theme = {
        "wallpaper": str(wp),
        "dominant": dom_hex, "accent": acc_hex,
        "dominant_variants": variants(dom_hex),
        "accent_variants": variants(acc_hex),
        "background": "#0a0e24" if sum(dom) < 300 else dom_hex,
        "source": "Pillow getcolors() on a 96px thumbnail; tonal variants via colorsys HLS",
        "blur": "pre-rendered (sway has no live blur)",
    }
    (outdir / "theme.json").write_text(json.dumps(theme, indent=2))
    css = ("/* generated by aegis-colours.py — do not hand-edit; re-run on wallpaper change */\n"
           f"@define-color aegis_accent {acc_hex};\n@define-color aegis_dominant {dom_hex};\n"
           f"@define-color aegis_accent_light {theme['accent_variants']['light']};\n"
           f"@define-color aegis_accent_dark {theme['accent_variants']['dark']};\n"
           f"@define-color aegis_bg {theme['background']};\n")
    (outdir / "theme.css").write_text(css)
    blurred = img.filter(ImageFilter.GaussianBlur(28))
    blurred.save(outdir / "blurred.png")
    top = img.crop((0, 0, img.width, 120)).filter(ImageFilter.GaussianBlur(24))
    top.save(outdir / "blurred-top.png")
    print(f"aegis-colours: wallpaper={wp}")
    print(f"  dominant={dom_hex} accent={acc_hex}")
    print(f"  wrote {outdir/'theme.json'}, theme.css, blurred.png, blurred-top.png")
    return 0

if __name__ == "__main__":
    sys.exit(main())
